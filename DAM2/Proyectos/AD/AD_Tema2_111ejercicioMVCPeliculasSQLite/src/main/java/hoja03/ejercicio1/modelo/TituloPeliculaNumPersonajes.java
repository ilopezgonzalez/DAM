public class TituloPeliculaNumPersonajes {
    
    private String title;
    private int numChar;

    public TituloPeliculaNumPersonajes(String title, int numChar) {
        this.title = title;
        this.numChar = numChar;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public int getNumChar() {
        return numChar;
    }

    public void setNumChar(int numChar) {
        this.numChar = numChar;
    }
    
    
    
}
