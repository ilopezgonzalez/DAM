public class Dimensiones {
    
    private int anchura;
    private int altura;

    public Dimensiones(int anchura, int altura) {
        this.anchura = anchura;
        this.altura = altura;
    }

    public Dimensiones() {
        this.anchura=0;
        this.altura=0;
    }

    public int getAnchura() {
        return anchura;
    }

    public void setAnchura(int anchura) {
        this.anchura = anchura;
    }

    public int getAltura() {
        return altura;
    }

    public void setAltura(int altura) {
        this.altura = altura;
    }
    
    
    
    
    
}
