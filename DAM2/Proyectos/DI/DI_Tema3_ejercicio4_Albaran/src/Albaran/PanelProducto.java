    public Producto getPropiedadSeleccionada() {
        // Validar nombre
        String nombre = campoNombre.getText().trim();
        if (nombre.isEmpty()) {
            return null;
        }

        // Validar tipo
        String tipo = comboTipo.getSelectedItem().toString();
        if (tipo.equals("<Seleccionar>")) {
            return null;
        }

        // Obtener unidades
        int unidades = sliderUnidades.getValue();

        // Crear y devolver el objeto
        return new Producto(nombre, tipo, unidades);
    }

