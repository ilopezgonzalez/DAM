    private void botonEnviarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonEnviarActionPerformed
        String marca = campoTextoMarca.getText();
        String envase = comboEnvase.getSelectedItem().toString();
        int litros = Integer.parseInt(spinnerLitros.getValue().toString());
        LocalDate fecha = LocalDate.now();

        DefaultTableModel modelo = (DefaultTableModel) tabla.getModel();
        String[] datos = new String[4];
        if (!marca.isEmpty() && !envase.isEmpty() && litros != 0) {
            datos[0] = marca;
            datos[1] = envase;
            datos[2] = String.valueOf(litros);
            datos[3] = String.valueOf(fecha);
            modelo.addRow(datos);
            campoTextoMarca.setText("");
            comboEnvase.setSelectedIndex(0);
            spinnerLitros.setValue(1);
        }

    }//GEN-LAST:event_botonEnviarActionPerformed

    private void tablaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaMouseClicked
        int filaSeleccionada = tabla.getSelectedRow();
        if (filaSeleccionada == ultimaFilaSeleccionada) {
            tabla.clearSelection();
            ultimaFilaSeleccionada = -1;
        } else {
            ultimaFilaSeleccionada = filaSeleccionada;
        }
    }//GEN-LAST:event_tablaMouseClicked

    private void botonEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonEliminarActionPerformed
        int filaSeleccionada = tabla.getSelectedRow();
        if (filaSeleccionada != -1) {
            DefaultTableModel modelo = (DefaultTableModel) tabla.getModel();
            modelo.removeRow(filaSeleccionada);

        }
    }//GEN-LAST:event_botonEliminarActionPerformed

