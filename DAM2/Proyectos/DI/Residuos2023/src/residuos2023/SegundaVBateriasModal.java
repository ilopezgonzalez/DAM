    private void sliderCapacidadMouseReleased(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_sliderCapacidadMouseReleased
        if (sliderCapacidad.getValue() > 30) {
            JOptionPane.showMessageDialog(this, "Se cobrará un recargo porque la batería es de más de 30A", "Atención", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_sliderCapacidadMouseReleased

    private void comboTipoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_comboTipoActionPerformed
        if (comboTipo.getSelectedIndex() == 0) {
            checkBoxDefectuosa.setEnabled(false);
            checkBoxCargada.setEnabled(false);
            checkBoxSoldada.setEnabled(false);
            radioAA.setEnabled(false);
            radioAAA.setEnabled(false);
            radioC.setEnabled(false);
            spinnerCantidad.setEnabled(false);
            sliderCapacidad.setEnabled(false);
        } else {
            checkBoxDefectuosa.setEnabled(true);
            checkBoxCargada.setEnabled(true);
            checkBoxSoldada.setEnabled(true);
            radioAA.setEnabled(true);
            radioAAA.setEnabled(true);
            radioC.setEnabled(true);
            spinnerCantidad.setEnabled(true);
            sliderCapacidad.setEnabled(true);
        }
        if (comboTipo.getSelectedIndex() == 3) {
            spinnerCantidad.setModel(new javax.swing.SpinnerNumberModel(3, 3, 10, 1));

        } else {
            spinnerCantidad.setModel(new javax.swing.SpinnerNumberModel(1, 1, 10, 1));

        }
    }//GEN-LAST:event_comboTipoActionPerformed

