-- Script de creación para MariaDB/MySQL para la aplicación eNativo
-- Crea la base de datos y las tablas: DIRECCION, PERSONA, TELEFONO

-- Cambia el nombre de la base de datos si lo deseas (actual: enativo_db)
CREATE DATABASE IF NOT EXISTS `enativo_db` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `enativo_db`;

-- Tabla DIRECCION
CREATE TABLE IF NOT EXISTS `DIRECCION` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `CALLE` VARCHAR(255) NOT NULL,
  `CIUDAD` VARCHAR(100),
  PRIMARY KEY (`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Tabla PERSONA
CREATE TABLE IF NOT EXISTS `PERSONA` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `NOMBRE` VARCHAR(100) NOT NULL,
  `EDAD` INT,
  `DIRECCION_ID` BIGINT,
  PRIMARY KEY (`ID`),
  INDEX `IDX_PERSONA_DIRECCION` (`DIRECCION_ID`),
  CONSTRAINT `FK_PERSONA_DIRECCION` FOREIGN KEY (`DIRECCION_ID`) REFERENCES `DIRECCION`(`ID`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Tabla TELEFONO
CREATE TABLE IF NOT EXISTS `TELEFONO` (
  `ID` BIGINT NOT NULL AUTO_INCREMENT,
  `NUMERO` VARCHAR(50) NOT NULL,
  `PERSONA_ID` BIGINT,
  PRIMARY KEY (`ID`),
  INDEX `IDX_TELEFONO_PERSONA` (`PERSONA_ID`),
  CONSTRAINT `FK_TELEFONO_PERSONA` FOREIGN KEY (`PERSONA_ID`) REFERENCES `PERSONA`(`ID`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

