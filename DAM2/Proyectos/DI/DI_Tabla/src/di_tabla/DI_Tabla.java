    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        DefaultTableModel modelo=(DefaultTableModel) jTable1.getModel();
        int fila=jTable1.getSelectedRow();
        if (fila<0) {
            JOptionPane.showMessageDialog(null, "Ninguna fila seleccionada");
        }else{
            int resultado=JOptionPane.showConfirmDialog(this, "¿Desea borrar la fila?", "Borrar fila", JOptionPane.YES_NO_OPTION);
            if (resultado==JOptionPane.YES_OPTION) {
                modelo.removeRow(fila);
                JOptionPane.showMessageDialog(this, "Fila Borrada");
            }else{
                JOptionPane.showMessageDialog(this, "No se borra la fila");
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        
        DefaultTableModel modelo = new DefaultTableModel();
        modelo = (DefaultTableModel)jTable1.getModel();
        String[] datos = new String[3];
        String nombre = jTextField1.getText();
        String apellido = jTextField2.getText();
        String provincia = jComboBox1.getSelectedItem().toString();
        int positem=jComboBox1.getSelectedIndex();
        if (!nombre.isEmpty()&&!apellido.isEmpty()&&positem>0) {
            datos[0]=nombre;
            datos[1]=apellido;
            datos[2]=provincia;
            modelo.addRow(datos);
            jTextField1.setText("");
            jTextField2.setText("");
            jComboBox1.setSelectedIndex(0);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

